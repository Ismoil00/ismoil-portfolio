"""Where uploaded files live. Same interface for the local disk (development), any S3-compatible server
(MinIO, RustFS, SeaweedFS, Garage, Cloudflare R2, AWS S3) and Vercel Blob — switched with STORAGE_BACKEND.

Browsers always load files straight from the storage (`url()`); the backend only writes and deletes them.
"""

import asyncio
import os
import re
import shutil
from datetime import datetime
from pathlib import Path
from types import ModuleType
from typing import BinaryIO, Protocol
from urllib.parse import quote

import aioboto3
import vercel.blob as vercel_blob
from botocore.exceptions import ClientError
from vercel.blob import BlobNotFoundError

from app.core.config import Settings
from app.core.files import content_disposition

# Keys are generated by the app ("project_image/<hex>.png"), never taken from the uploader.
_KEY = re.compile(r"[a-z_]+/[A-Za-z0-9_-]+\.[a-z0-9]+")
# Files kept forever under names that are never reused: browsers and CDNs may cache them for a year.
YEAR = 365 * 24 * 3600


class InvalidKey(ValueError):
    pass


def _check_key(key: str) -> str:
    if not _KEY.fullmatch(key or ""):
        raise InvalidKey(f"Invalid storage key: {key!r}")
    return key


class Storage(Protocol):
    # True when the browser uploads big files straight to the storage (see DirectUploadStorage).
    direct_uploads: bool

    async def save(self, key: str, data: BinaryIO, content_type: str, *, download_name: str | None = None) -> None:
        """download_name: save-as name for files meant to be downloaded (the résumé); None for files shown inline.
        Pass the same name to url(), exists() and delete()."""

    async def delete(self, key: str, *, download_name: str | None = None) -> None: ...
    async def exists(self, key: str, *, download_name: str | None = None) -> bool: ...
    def url(self, key: str, *, download_name: str | None = None) -> str: ...


class DirectUploadStorage(Storage, Protocol):
    """A storage the admin panel uploads to directly. Uploads land on a staging path
    (`incoming/<purpose>/<32 hex>`); the backend then checks the file and moves it to its key."""

    def is_staged(self, pathname: str) -> bool: ...
    async def staged_size(self, pathname: str) -> int | None: ...
    async def read_staged(self, pathname: str, limit: int | None = None) -> bytes: ...
    async def adopt_staged(
        self, pathname: str, key: str, content_type: str, *, download_name: str | None = None
    ) -> None: ...
    async def discard_staged(self, pathname: str) -> None: ...
    async def stale_staged(self, before: datetime) -> list[str]: ...


class LocalStorage:
    direct_uploads = False

    def __init__(self, root: Path, base_url: str) -> None:
        self.root = root.resolve()
        self.base_url = base_url.rstrip("/")

    def path(self, key: str) -> Path:
        path = (self.root / _check_key(key)).resolve()
        if not path.is_relative_to(self.root):
            raise InvalidKey(f"Invalid storage key: {key!r}")
        return path

    async def save(self, key: str, data: BinaryIO, content_type: str, *, download_name: str | None = None) -> None:
        # The download name comes from the database when the file is served (api/media_files.py).
        path = self.path(key)

        def write() -> None:
            path.parent.mkdir(parents=True, exist_ok=True)
            with path.open("wb") as target:
                shutil.copyfileobj(data, target, length=1024 * 1024)

        await asyncio.to_thread(write)

    async def delete(self, key: str, *, download_name: str | None = None) -> None:
        await asyncio.to_thread(self.path(key).unlink, missing_ok=True)

    async def exists(self, key: str, *, download_name: str | None = None) -> bool:
        return await asyncio.to_thread(self.path(key).is_file)

    def url(self, key: str, *, download_name: str | None = None) -> str:
        return f"{self.base_url}/{_check_key(key)}"


class S3Storage:
    direct_uploads = False

    def __init__(
        self,
        *,
        endpoint_url: str | None,
        bucket: str,
        access_key: str | None,
        secret_key: str | None,
        region: str,
        public_base_url: str,
    ) -> None:
        self.endpoint_url = endpoint_url
        self.bucket = bucket
        self.public_base_url = public_base_url.rstrip("/")
        self._session = aioboto3.Session(
            aws_access_key_id=access_key, aws_secret_access_key=secret_key, region_name=region
        )

    def _client(self):
        return self._session.client("s3", endpoint_url=self.endpoint_url)

    async def ensure_bucket(self) -> None:
        async with self._client() as client:
            try:
                await client.head_bucket(Bucket=self.bucket)
            except ClientError:
                await client.create_bucket(Bucket=self.bucket)

    async def save(self, key: str, data: BinaryIO, content_type: str, *, download_name: str | None = None) -> None:
        # The storage server serves the file itself, so the save-as name travels with the file.
        extra = {"ContentType": content_type}
        if download_name:
            extra["ContentDisposition"] = content_disposition(download_name)
        async with self._client() as client:
            await client.upload_fileobj(data, self.bucket, _check_key(key), ExtraArgs=extra)

    async def delete(self, key: str, *, download_name: str | None = None) -> None:
        async with self._client() as client:
            await client.delete_object(Bucket=self.bucket, Key=_check_key(key))

    async def exists(self, key: str, *, download_name: str | None = None) -> bool:
        async with self._client() as client:
            try:
                await client.head_object(Bucket=self.bucket, Key=_check_key(key))
            except ClientError:
                return False
            return True

    def url(self, key: str, *, download_name: str | None = None) -> str:
        return f"{self.public_base_url}/{_check_key(key)}"


# Characters kept in a Blob file name; anything else (#, ?, %, slashes…) would change the URL's meaning.
_BLOB_UNSAFE = re.compile(r"[^\w .,()\[\]+&'!@=~-]")
_STAGED = re.compile(r"incoming/[a-z_]+/[0-9a-f]{32}")
STAGING_PREFIX = "incoming/"


def blob_file_name(name: str) -> str:
    """A download name as a Blob path segment: letters in any alphabet, digits, spaces and common
    punctuation are kept; other characters become "_"."""
    name = _BLOB_UNSAFE.sub("_", name).strip()
    stem, dot, extension = name.rpartition(".")
    if dot and not stem.strip(" ."):
        name = f"file.{extension}" if extension else "file"
    return name if name.strip(".") else "file"


class BlobStorage:
    """Vercel Blob, in a public store. Files are served by Vercel's CDN at `<base url>/<path>`.

    Blob names a download after the file's path, so a file with a download name (the résumé) is stored as
    `resume/<hex>/<name>` and linked with `?download=1`; everything else is stored under its key.
    `client` is the `vercel.blob` module (tests pass a fake); it reads BLOB_READ_WRITE_TOKEN.
    """

    direct_uploads = True

    def __init__(self, public_base_url: str, *, client: ModuleType | object | None = None) -> None:
        self.public_base_url = public_base_url.rstrip("/")
        self.client = client or vercel_blob

    def pathname(self, key: str, download_name: str | None = None) -> str:
        key = _check_key(key)
        return f"{key.rsplit('.', 1)[0]}/{blob_file_name(download_name)}" if download_name else key

    async def save(self, key: str, data: BinaryIO, content_type: str, *, download_name: str | None = None) -> None:
        body = await asyncio.to_thread(data.read)
        await self.client.put_blob(
            self.pathname(key, download_name),
            body,
            access="public",
            content_type=content_type,
            allow_overwrite=True,
            cache_control_max_age=YEAR,
        )

    async def delete(self, key: str, *, download_name: str | None = None) -> None:
        await self.client.delete_blob(self.pathname(key, download_name))

    async def exists(self, key: str, *, download_name: str | None = None) -> bool:
        try:
            await self.client.head_blob(self.pathname(key, download_name))
        except BlobNotFoundError:
            return False
        return True

    def url(self, key: str, *, download_name: str | None = None) -> str:
        url = f"{self.public_base_url}/{quote(self.pathname(key, download_name))}"
        return f"{url}?download=1" if download_name else url

    # Direct uploads (DirectUploadStorage)

    def is_staged(self, pathname: str) -> bool:
        return bool(_STAGED.fullmatch(pathname or ""))

    def _staged(self, pathname: str) -> str:
        if not self.is_staged(pathname):
            raise InvalidKey(f"Not a staging path: {pathname!r}")
        return pathname

    async def staged_size(self, pathname: str) -> int | None:
        try:
            return (await self.client.head_blob(self._staged(pathname))).size
        except BlobNotFoundError:
            return None

    async def read_staged(self, pathname: str, limit: int | None = None) -> bytes:
        """The whole file, or only its first `limit` bytes (enough to recognize its type)."""
        if limit is None:
            return (await self.client.get_blob(self._staged(pathname), access="public")).body
        received = bytearray()
        async with self.client.stream_blob(self._staged(pathname), access="public") as download:
            async for chunk in download:
                received.extend(chunk)
                if len(received) >= limit:
                    break
        return bytes(received[:limit])

    async def adopt_staged(
        self, pathname: str, key: str, content_type: str, *, download_name: str | None = None
    ) -> None:
        """Moves a checked upload to its key (a copy inside the store, then the staged file is removed)."""
        await self.client.copy_blob(
            self._staged(pathname),
            self.pathname(key, download_name),
            access="public",
            content_type=content_type,
            cache_control_max_age=YEAR,
        )
        await self.discard_staged(pathname)

    async def discard_staged(self, pathname: str) -> None:
        await self.client.delete_blob(self._staged(pathname))

    async def stale_staged(self, before: datetime) -> list[str]:
        """Staged uploads never checked in (the admin closed the page): removed by the daily cleanup."""
        return [
            blob.pathname
            async for blob in self.client.query_blobs(prefix=STAGING_PREFIX)
            if self.is_staged(blob.pathname) and blob.uploaded_at < before
        ]


_BLOB_TOKEN = re.compile(r"vercel_blob_rw_([A-Za-z0-9]+)_\S+")


def blob_public_base_url(settings: Settings) -> str:
    """Where a public Blob store serves files: MEDIA_BASE_URL when it's set to an https:// address, else
    https://<store id, lower case>.public.blob.vercel-storage.com, the store id taken from BLOB_STORE_ID or
    from the read-write token (vercel_blob_rw_<store id>_<secret>)."""
    if settings.media_base_url.startswith("https://"):
        return settings.media_base_url
    token = settings.blob_read_write_token.get_secret_value() if settings.blob_read_write_token else ""
    token = token or os.environ.get("BLOB_READ_WRITE_TOKEN", "")
    store = os.environ.get("BLOB_STORE_ID", "").strip().removeprefix("store_")
    if not store and (match := _BLOB_TOKEN.fullmatch(token.strip())):
        store = match.group(1)
    if not store:
        raise ValueError("STORAGE_BACKEND=blob needs BLOB_READ_WRITE_TOKEN (connect the Blob store to the project)")
    return f"https://{store.lower()}.public.blob.vercel-storage.com"


def create_storage(settings: Settings) -> Storage:
    if settings.storage_backend == "s3":
        return S3Storage(
            endpoint_url=settings.s3_endpoint_url,
            bucket=settings.s3_bucket,
            access_key=settings.s3_access_key.get_secret_value() if settings.s3_access_key else None,
            secret_key=settings.s3_secret_key.get_secret_value() if settings.s3_secret_key else None,
            region=settings.s3_region,
            public_base_url=settings.media_base_url,
        )
    if settings.storage_backend == "blob":
        base_url = blob_public_base_url(settings)
        if settings.blob_read_write_token:
            # The Blob SDK reads its token from the environment; backend/.env isn't part of it.
            os.environ.setdefault("BLOB_READ_WRITE_TOKEN", settings.blob_read_write_token.get_secret_value())
        return BlobStorage(base_url)
    return LocalStorage(settings.local_storage_dir, settings.media_base_url)
