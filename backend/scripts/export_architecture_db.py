"""Writes the database data of the architecture site from the SQLAlchemy models.

Run from backend/:  .venv/Scripts/python scripts/export_architecture_db.py
Output: architecture_visually_explained/data/db-schema.generated.js (do not edit it by hand).
tests_architecture/test_architecture_db.py fails while that file is out of date
(run on its own: .venv/Scripts/python -m pytest tests_architecture).
"""

import inspect
import json
import sys
from pathlib import Path
from typing import Any

BACKEND = Path(__file__).resolve().parents[1]
if str(BACKEND) not in sys.path:
    sys.path.insert(0, str(BACKEND))  # run as a script: make `app` importable

from sqlalchemy import CheckConstraint, Column, Table, UniqueConstraint  # noqa: E402
from sqlalchemy.dialects import postgresql  # noqa: E402

import app.models  # noqa: E402, F401  (registers every table)
from app.db.base import Base  # noqa: E402

OUTPUT = BACKEND.parent / "architecture_visually_explained" / "data" / "db-schema.generated.js"
DIALECT = postgresql.dialect()
HEADER = (
    "// Generated by backend/scripts/export_architecture_db.py from the SQLAlchemy models. Do not edit by hand.\n"
    "window.ARCH = window.ARCH || {};\n"
)


def _sql(value: Any) -> str:
    return str(value.compile(dialect=DIALECT, compile_kwargs={"literal_binds": True}))


def _default(column: Column) -> str | None:
    if column.server_default is not None:
        arg = column.server_default.arg  # type: ignore[attr-defined]
        return _sql(arg) if hasattr(arg, "compile") else str(arg)
    if column.default is not None and callable(column.default.arg):  # type: ignore[attr-defined]
        return f"{column.default.arg.__name__}() in Python"  # type: ignore[attr-defined]
    if column.primary_key and column.autoincrement is not False and column.type.python_type is int:
        return f"nextval('{column.table.name}_id_seq')"
    return None


def _models() -> dict[str, tuple[str, str, str]]:
    """table name -> (model class, module file, first paragraph of the class docstring)."""
    found = {}
    for mapper in Base.registry.mappers:
        cls = mapper.class_
        own = cls.__dict__.get("__doc__")  # not the docstring inherited from the declarative base
        doc = (inspect.cleandoc(own) if own else "").split("\n\n")[0].replace("\n", " ")
        module = cls.__module__.replace(".", "/") + ".py"
        found[mapper.local_table.name] = (cls.__name__, module, doc)
    return found


def _table(table: Table, models: dict[str, tuple[str, str, str]]) -> dict[str, Any]:
    single_unique = {
        next(iter(c.columns)).name for c in table.constraints if isinstance(c, UniqueConstraint) and len(c.columns) == 1
    }
    single_unique |= {  # a partial unique index (WHERE …) doesn't make the whole column unique
        next(iter(i.columns)).name
        for i in table.indexes
        if i.unique and len(i.columns) == 1 and i.dialect_options["postgresql"]["where"] is None
    }
    model, module, doc = models.get(table.name, (None, "app/models/links.py", table.comment or ""))
    return {
        "name": table.name,
        "model": model,
        "module": module,
        "doc": doc,
        "columns": [
            {
                "name": c.name,
                "type": c.type.compile(dialect=DIALECT),
                "nullable": bool(c.nullable),
                "pk": c.primary_key,
                "unique": c.name in single_unique,
                "default": _default(c),
                "onUpdate": _sql(c.onupdate.arg) if c.onupdate is not None else None,  # type: ignore[attr-defined]
                "fk": next(
                    (
                        {
                            "table": fk.column.table.name,
                            "column": fk.column.name,
                            "onDelete": fk.ondelete or "NO ACTION",
                        }
                        for fk in c.foreign_keys
                    ),
                    None,
                ),
            }
            for c in table.columns
        ],
        "foreignKeys": sorted(
            (
                {
                    "name": str(fk.constraint.name),
                    "columns": [fk.parent.name],
                    "table": fk.column.table.name,
                    "refColumns": [fk.column.name],
                    "onDelete": fk.ondelete or "NO ACTION",
                }
                for fk in table.foreign_keys
            ),
            key=lambda fk: fk["name"],
        ),
        "checks": sorted(
            (
                {"name": str(c.name), "sql": _sql(c.sqltext)}
                for c in table.constraints
                if isinstance(c, CheckConstraint)
            ),
            key=lambda c: c["name"],
        ),
        "uniques": sorted(
            (
                {"name": str(c.name), "columns": [col.name for col in c.columns]}
                for c in table.constraints
                if isinstance(c, UniqueConstraint)
            ),
            key=lambda c: c["name"],
        ),
        "indexes": sorted(
            (
                {
                    "name": str(i.name),
                    "columns": [col.name for col in i.columns],
                    "unique": bool(i.unique),
                    "where": _sql(where) if (where := i.dialect_options["postgresql"]["where"]) is not None else None,
                }
                for i in table.indexes
            ),
            key=lambda i: i["name"],
        ),
    }


def schema() -> dict[str, Any]:
    models = _models()
    return {
        "source": "backend/app/models",
        "schema": "work",
        "tables": [_table(table, models) for table in sorted(Base.metadata.tables.values(), key=lambda t: t.name)],
    }


def render() -> str:
    return HEADER + "window.ARCH.dbSchema = " + json.dumps(schema(), indent=1, ensure_ascii=False) + ";\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(render(), encoding="utf-8", newline="\n")
    print(f"Wrote {OUTPUT.relative_to(BACKEND.parent)} ({len(schema()['tables'])} tables)")


if __name__ == "__main__":
    main()
